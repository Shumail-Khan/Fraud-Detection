"""
Data preprocessing and pipeline transformations.
"""

from typing import Tuple
import pandas as pd
from sklearn.model_selection import train_test_split

from fraud_detection.utils.logger import setup_logger

logger = setup_logger(__name__)

ALL_TRANSACTION_TYPES = ["CASH_OUT", "TRANSFER", "PAYMENT", "DEBIT", "CASH_IN"]


class DataPreprocessor:
    """Preprocesses transaction records for feature engineering and modeling."""

    def __init__(self, test_size: float = 0.2, random_state: int = 42):
        self.test_size = test_size
        self.random_state = random_state

    def encode_transaction_types(self, df: pd.DataFrame) -> pd.DataFrame:
        """One-hot encodes the transaction type with consistent columns across train/inference."""
        df = df.copy()
        if "type" in df.columns:
            for tx_type in ALL_TRANSACTION_TYPES:
                col_name = f"type_{tx_type}"
                df[col_name] = (df["type"] == tx_type).astype(int)
        return df

    def handle_missing(self, df: pd.DataFrame) -> pd.DataFrame:
        """Fills numerical NaNs or inf values generated by division."""
        df = df.copy()
        # Replace inf with nan and fill with median/0
        numeric_cols = df.select_dtypes(include=["number"]).columns
        df[numeric_cols] = df[numeric_cols].replace([float("inf"), float("-inf")], float("nan"))
        df[numeric_cols] = df[numeric_cols].fillna(0.0)
        return df

    def split_data(
        self, df: pd.DataFrame, target_col: str = "isFraud"
    ) -> Tuple[pd.DataFrame, pd.DataFrame]:
        """Performs a stratified train/test split to preserve class imbalance ratios."""
        logger.info(f"Splitting dataset with test_size={self.test_size}, random_state={self.random_state}")
        train_df, test_df = train_test_split(
            df,
            test_size=self.test_size,
            random_state=self.random_state,
            stratify=df[target_col] if target_col in df.columns else None,
        )
        logger.info(
            f"Split complete. Train set: {len(train_df):,} samples, Test set: {len(test_df):,} samples."
        )
        return train_df.reset_index(drop=True), test_df.reset_index(drop=True)
